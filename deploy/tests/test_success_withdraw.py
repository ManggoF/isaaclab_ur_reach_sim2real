    def test_reset_starts_in_completion_callback_and_plots_only_after_reset(self):
        node = OfflineDeployNode()
        node.begin_withdrawal()
        with patch("subprocess.Popen") as new_process:
            for _ in range(30):
                node.tick()
                node.save_safety_gain_curve_outputs.assert_not_called()
                node.save_joint_angle_curve.assert_not_called()
                if node.success_withdraw_complete:
                    break
            self.assertTrue(node.success_withdraw_complete)
            self.assertTrue(node.reset_started)
            self.assertEqual(node.reset_start_time_ns, node.now_ns)
            self.assertEqual(node.fsm_state, "RESET")
            self.assertEqual(len(node.commands), 2, "One withdrawal and one reset, with no intervening hold")
            self.assertTrue(np.allclose(node.commands[-1], node.DEFAULT_JOINT_POS))
            self.assertGreaterEqual(node.command_durations[-1], node.RESET_MIN_DURATION_S)
            new_process.assert_not_called()

        # Receiving the default pose, rather than sending it, completes reset.
        node.tick()
        self.assertFalse(node.reset_finished)
        node.current_joint_pos = node.DEFAULT_JOINT_POS.copy()
        for _ in range(math.ceil(node.RESET_SETTLE_TIME_S / node.control_period) + 2):
            node.tick()
        self.assertTrue(node.reset_finished)
        self.assertEqual(node.fsm_state, "DONE")
        self.assertEqual(len(node.commands), 2, "Monitoring must not replace the reset trajectory")
        node.save_safety_gain_curve_outputs.assert_called_once_with("SUCCESS")
        node.save_joint_angle_curve.assert_called_once()
        node.tick()
        node.save_joint_angle_curve.assert_called_once()
        node.policy.act.assert_not_called()
        node.safety_policy.act.assert_not_called()

    def test_scaled_withdrawal_and_reset_finish_without_plotting_during_motion(self):
        node = TimedTrajectoryDeployNode(scaling=0.55, interpolation="cubic")
        node.current_joint_pos = np.array([0.19602, -0.93687, 1.43608, -0.58323, 0.76631, 0.06622])
        node.begin_withdrawal()
        for _ in range(1800):
            node.tick()
            if node.reset_finished:
                break
            node.save_joint_angle_curve.assert_not_called()
            node.save_safety_gain_curve_outputs.assert_not_called()
        self.assertTrue(node.success_withdraw_complete)
        self.assertTrue(node.reset_finished)
        self.assertEqual(node.fsm_state, "DONE")
        self.assertEqual(len(node.trajectories), 2)
        self.assertLess(np.max(np.abs(node.current_joint_pos - node.DEFAULT_JOINT_POS)), node.RESET_GOAL_TOL_RAD)
        node.save_joint_angle_curve.assert_called_once()

    def test_stalled_reset_times_out_and_saves_without_resending(self):
        node = OfflineDeployNode(follow_commands=False)
        node.success_withdraw_complete = True
        node.episode_stopped = True
        self.assertTrue(node.start_reset_after_success())
        for _ in range(30):
            node.tick()
        self.assertFalse(node.reset_finished)
        self.assertEqual(len(node.commands), 1)
        node.save_joint_angle_curve.assert_not_called()
        node.now_ns += round(node.reset_timeout_s * 1e9)
        node.tick()
        self.assertTrue(node.reset_finished)
        self.assertEqual(node.fsm_state, "RESET_FAILED")
        self.assertEqual(len(node.commands), 2, "The second command is the timeout hold")
        self.assertTrue(np.allclose(node.commands[-1], node.current_joint_pos))
        node.save_joint_angle_curve.assert_called_once()

    def test_stale_joint_feedback_cannot_confirm_reset_completion(self):
        node = OfflineDeployNode(follow_commands=False)
        node.success_withdraw_complete = True
        self.assertTrue(node.start_reset_after_success())
        node.current_joint_pos = node.DEFAULT_JOINT_POS.copy()
        node.now_ns += round((node.args.joint_state_timeout + 1.0) * 1e9)
        node.update_reset_after_success()
        self.assertFalse(node.reset_finished)
        self.assertIsNone(node.reset_reached_since_ns)
        node.save_joint_angle_curve.assert_not_called()


