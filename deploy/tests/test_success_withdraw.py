class OfflineDeployNode(ArmPolicyDeployNode):
    def __init__(self, follow_commands: bool = True, dry_run: bool = False) -> None:
        # Do not initialize rclpy.Node: all feedback is generated by local FK.
        self.now_ns = 10_000_000_000
        self.args = SimpleNamespace(
            dry_run=dry_run,
            withdraw_distance=0.10,
            max_cartesian_step=0.042,
            max_rotation_step=0.042,
            max_joint_step=math.radians(2.0),
            joint_state_timeout=0.5,
            fixed_mouth_pose=True,
            target_timeout=0.5,
            wrench_bias_samples=0,
            wrench_timeout=0.5,
            min_trajectory_duration=0.08,
        )
        self.control_period = 1.0 / 30.0
        self.ik = UR5eDLSIK()
        # Reachable insertion pose with tool +Z aligned with the fixed mouth axis.
        self.current_joint_pos = np.array(
            [0.09724781689590194, -0.7128700779136284, 0.9732295994897862,
             -0.2603595215761593, 0.35638860651222326, 0.0], dtype=np.float64
        )
        self.current_joint_vel = np.zeros(6)
        self.mouth_pos = self.DEFAULT_FIXED_MOUTH_POS.astype(np.float64)
        self.mouth_axis = self.DEFAULT_FIXED_MOUTH_AXIS.astype(np.float64)
        self.mouth_axis /= np.linalg.norm(self.mouth_axis)
        self.target_received = True
        self.episode_stopped = False
        self.episode_stop_reason = None
        self.episode_start_time_ns = self.now_ns
        self.reset_started = False
        self.reset_finished = False
        self.reset_start_time_ns = None
        self.reset_reached_since_ns = None
        self.reset_timeout_s = 0.0
        self.fsm_state = "APPROACH"
        self.feed_stable_steps = 0
        self.success_hold_steps = 0
        self.success_hold_joint_pos = None
        self.success_withdraw_start_spoon = None
        self.success_withdraw_direction = None
        self.success_withdraw_quat_wxyz = None
        self.success_withdraw_start_time_ns = None
        self.success_withdraw_stable_steps = 0
        self.success_withdraw_complete = False
        self.success_withdraw_trajectory_sent = False
        self.safety_strengthen_active = False
        self.withdrawal_reason = "SUCCESS"
        self.withdraw_distance_m = self.args.withdraw_distance
        self.speed_scaling = 1.0
        self.previous_arm_action = np.zeros(6)
        self.previous_safety_action = np.zeros(3)
        self.safety_slow_active = False
        self.rule_safety_retreat_active = False
        self.rule_safety_retreat_steps = 0
        self.rule_safety_enabled = False
        self.learned_safety_enabled = False
        self.rule_safety_last_state = self.default_rule_safety_state()
        self.save_full_safety_gain_curve = True
        self.safety_gain_curve_rows = []
        self.update_safety_gain_visualization = Mock()
        self.policy_step = 0
        self.last_fsm_metrics = {}
        self.last_joint_state_time_ns = self.now_ns
        self.last_wrench_time_ns = self.now_ns
        self.last_face_time_ns = None
        self.policy = Mock()
        self.safety_policy = Mock()
        self.logger = Mock()
        self.follow_commands = follow_commands
        self.commands = []
        self.command_durations = []
        self.trajectories = []
        self.pub = SimpleNamespace(publish=self.receive_trajectory)
        self.data_is_stale = Mock(return_value=False)
        self.ros_control_is_ready = Mock(return_value=True)
        self.save_safety_gain_curve_outputs = Mock()
        self.save_joint_angle_curve = Mock()

    def get_clock(self):
        return SimpleNamespace(now=lambda: SimpleNamespace(nanoseconds=self.now_ns))

    def get_logger(self):
        return self.logger

    def compute_mouth_axis(self, invert=True):
        return self.mouth_axis.copy() if invert else -self.mouth_axis

    def lookup_ee_pose(self, require_fresh=False):
        pos, rot = self.ik.fk(self.current_joint_pos)
        ros_frame = R.from_rotvec([0.0, 0.0, math.pi])
        quat_xyzw = (ros_frame * rot).as_quat()
        return ros_frame.apply(pos), quat_xyzw[[3, 0, 1, 2]]

    def publish_joint_target(self, joint_target, min_duration_s=0.0):
        self.commands.append(np.asarray(joint_target).copy())
        self.command_durations.append(min_duration_s)
        if self.follow_commands and self.fsm_state != "RESET":
            self.current_joint_pos = np.asarray(joint_target).copy()

    def receive_trajectory(self, message):
        self.trajectories.append(message)
        point = message.points[-1]
        duration = point.time_from_start.sec + point.time_from_start.nanosec * 1e-9
        self.publish_joint_target(np.asarray(point.positions), min_duration_s=duration)

    def spoon_pose(self):
        ee_pos, quat = self.lookup_ee_pose()
        return ee_pos + quat_apply_wxyz(quat, self.SPOON_OFFSET), quat

    def tick(self):
        self.now_ns += round(self.control_period * 1e9)
        self.last_joint_state_time_ns = self.now_ns
        self.step_callback()

    def begin_withdrawal(self):
        spoon, quat = self.spoon_pose()
        self.start_success_withdraw(spoon, quat)


class TimedTrajectoryDeployNode(OfflineDeployNode):
    """Consume actual trajectory messages with scaling and a dispatch delay.

    Replacing a message restarts its clock, unlike the instantaneous feedback
    fake above. Position-only points use linear interpolation; points with
    velocities also exercise cubic interpolation without a ROS controller.
    """

    def __init__(self, scaling=0.55, interpolation="linear"):
        super().__init__(follow_commands=False)
        self.scaling = scaling
        self.speed_scaling = scaling * 100.0
        self.interpolation = interpolation
        self.trajectory_target = None
        self.trajectory_start = None
        self.trajectory_elapsed = 0.0
        self.trajectory_duration = 0.0
        self.dispatch_delay = 0.0

    def publish_joint_target(self, joint_target, min_duration_s=0.0):
        ArmPolicyDeployNode.publish_joint_target(self, joint_target, min_duration_s=min_duration_s)

    def receive_trajectory(self, message):
        self.trajectories.append(message)
        point = message.points[-1]
        self.trajectory = message
        self.trajectory_times = np.array([
            point.time_from_start.sec + point.time_from_start.nanosec * 1e-9 for point in message.points
        ])
        self.trajectory_start = self.current_joint_pos.copy()
        self.trajectory_target = np.asarray(point.positions)
        self.trajectory_duration = point.time_from_start.sec + point.time_from_start.nanosec * 1e-9
        self.trajectory_elapsed = 0.0
        self.dispatch_delay = self.control_period
        self.commands.append(self.trajectory_target.copy())
        self.command_durations.append(self.trajectory_duration)

    def tick(self):
        previous = self.current_joint_pos.copy()
        if self.trajectory_target is not None:
            if self.dispatch_delay > 0.0:
                self.dispatch_delay -= self.control_period
            else:
                self.trajectory_elapsed += self.control_period * self.scaling
                index = int(np.searchsorted(self.trajectory_times, self.trajectory_elapsed, side="right"))
                if index >= len(self.trajectory.points):
                    self.current_joint_pos = self.trajectory_target.copy()
                else:
                    end = self.trajectory.points[index]
                    start = self.trajectory.points[index - 1] if index > 0 else None
                    start_pos = np.asarray(start.positions) if start else self.trajectory_start
                    end_pos = np.asarray(end.positions)
                    start_time = self.trajectory_times[index - 1] if index > 0 else 0.0
                    interval = self.trajectory_times[index] - start_time
                    fraction = min((self.trajectory_elapsed - start_time) / interval, 1.0)
                    if self.interpolation == "cubic" and end.velocities:
                        start_vel = np.asarray(start.velocities) if start and start.velocities else np.zeros(6)
                        end_vel = np.asarray(end.velocities) if end.velocities else np.zeros(6)
                        self.current_joint_pos = (
                            (2 * fraction**3 - 3 * fraction**2 + 1) * start_pos
                            + (fraction**3 - 2 * fraction**2 + fraction) * interval * start_vel
                            + (-2 * fraction**3 + 3 * fraction**2) * end_pos
                            + (fraction**3 - fraction**2) * interval * end_vel
                        )
                    else:
                        self.current_joint_pos = start_pos + fraction * (end_pos - start_pos)
        self.current_joint_vel = (self.current_joint_pos - previous) / self.control_period
        super().tick()


class SuccessWithdrawTest(unittest.TestCase):
    def test_holds_then_withdraws_ten_cm_before_reset(self):
        node = OfflineDeployNode()
        node.start_success_hold()
        with patch("subprocess.Popen") as launch_reset:
            for _ in range(node.SUCCESS_HOLD_STEPS_AFTER_REACHED):
                node.tick()
            self.assertEqual(node.fsm_state, "SUCCESS_WITHDRAW")
            launch_reset.assert_not_called()
            start, start_quat = node.spoon_pose()
            direction = node.success_withdraw_direction.copy()
            lateral_errors = []
            rotation_errors = []
            for _ in range(600):
                node.tick()
                spoon, quat = node.spoon_pose()
                offset = spoon - start
                progress = float(offset @ direction)
                lateral_errors.append(np.linalg.norm(offset - progress * direction))
                rotation_errors.append((R.from_quat(quat[[1, 2, 3, 0]]) * R.from_quat(start_quat[[1, 2, 3, 0]]).inv()).magnitude())
                if not node.success_withdraw_complete:
                    self.assertFalse(node.reset_started)
                    launch_reset.assert_not_called()
                if node.episode_stopped:
                    break
            self.assertTrue(node.success_withdraw_complete)
            self.assertEqual(node.fsm_state, "RESET")
            self.assertAlmostEqual(progress, 0.10, delta=node.SUCCESS_WITHDRAW_POSITION_TOL_M)
            self.assertLess(max(lateral_errors), 0.001)
            self.assertLess(max(rotation_errors), math.radians(2.0))
            self.assertLess(node.last_fsm_metrics["mouth_depth"], 0.0)
            self.assertTrue(node.reset_started)
            self.assertTrue(np.allclose(node.commands[-1], node.DEFAULT_JOINT_POS))
            launch_reset.assert_not_called()
        node.policy.act.assert_not_called()
        node.safety_policy.act.assert_not_called()

    def test_stalled_feedback_never_counts_commands_as_actual_distance(self):
        node = OfflineDeployNode(follow_commands=False)
        node.begin_withdrawal()
        with patch("subprocess.Popen") as launch_reset:
            for _ in range(100):
                node.tick()
            self.assertFalse(node.success_withdraw_complete)
            self.assertFalse(node.episode_stopped)
            self.assertTrue(node.success_withdraw_trajectory_sent)
            self.assertEqual(len(node.trajectories), 1, "Publish the entire withdrawal only once")
            node.now_ns += round(node.SUCCESS_WITHDRAW_TIMEOUT_S * 1e9)
            node.tick()
            self.assertTrue(node.episode_stopped)
            launch_reset.assert_not_called()

    def test_single_trajectory_finishes_under_scaled_delayed_execution(self):
        recorded_q = np.array([0.19602, -0.93687, 1.43608, -0.58323, 0.76631, 0.06622])
        for scaling, interpolation, actual_pose in [
            (1.0, "linear", False),
            (1.0, "cubic", False),
            (0.55, "linear", False),
            (0.55, "cubic", True),
            (0.30, "linear", True),
            (0.30, "cubic", True),
        ]:
            with self.subTest(scaling=scaling, interpolation=interpolation, recorded_pose=actual_pose):
                node = TimedTrajectoryDeployNode(scaling=scaling, interpolation=interpolation)
                if actual_pose:
                    node.current_joint_pos = recorded_q.copy()
                node.begin_withdrawal()
                max_lateral_error = 0.0
                joint_speeds = []
                moving_speeds = []
                with patch("subprocess.Popen") as launch_reset:
                    for _ in range(900):
                        node.tick()
                        spoon, _ = node.spoon_pose()
                        displacement = spoon - node.success_withdraw_start_spoon
                        progress = float(displacement @ node.success_withdraw_direction)
                        lateral = np.linalg.norm(displacement - progress * node.success_withdraw_direction)
                        max_lateral_error = max(max_lateral_error, lateral)
                        joint_speeds.append(np.abs(node.current_joint_vel))
                        if 0.01 < progress < 0.09:
                            moving_speeds.append(float(np.linalg.norm(node.current_joint_vel)))
                        if not node.success_withdraw_complete:
                            self.assertFalse(node.reset_started)
                            launch_reset.assert_not_called()
                        if node.episode_stopped:
                            break
                    self.assertTrue(node.success_withdraw_complete)
                    self.assertAlmostEqual(progress, 0.1, delta=node.SUCCESS_WITHDRAW_POSITION_TOL_M)
                    self.assertLess(max_lateral_error, 0.001)
                    withdrawals = [message for message in node.trajectories if len(message.points) > 1]
                    self.assertEqual(len(withdrawals), 1)
                    self.assertLessEqual(np.max(joint_speeds / node.JOINT_MAX_VELOCITIES_RAD_S), 1.0001)
                    self.assertGreater(min(moving_speeds), 0.001, "No pauses between internal path samples")
                    elapsed = (node.now_ns - node.success_withdraw_start_time_ns) * 1e-9
                    self.assertLess(elapsed, 2.0 / scaling + 1.0)
                    self.assertTrue(node.reset_started)
                    launch_reset.assert_not_called()

    def test_joint_target_duration_and_joint_speed_limits_are_both_respected(self):
        node = OfflineDeployNode()
        node.pub = Mock()
        for delta, requested in [(0.001, 0.25), (1.0, 0.1)]:
            target = node.current_joint_pos.copy()
            target[0] += delta
            ArmPolicyDeployNode.publish_joint_target(node, target, min_duration_s=requested)
            point = node.pub.publish.call_args.args[0].points[0]
            duration = point.time_from_start.sec + point.time_from_start.nanosec * 1e-9
            self.assertGreaterEqual(duration, requested - 1e-9)
            self.assertGreaterEqual(duration, abs(delta) / node.JOINT_MAX_VELOCITIES_RAD_S[0] - 1e-9)

    def test_complete_path_has_smooth_velocities_and_exact_ten_cm_goal(self):
        node = OfflineDeployNode()
        start, start_quat = node.spoon_pose()
        node.begin_withdrawal()
        node.tick()
        self.assertEqual(len(node.trajectories), 1)
        message = node.trajectories[0]
        self.assertGreater(len(message.points), 2)
        self.assertEqual(list(message.points[0].velocities), [0.0] * 6)
        self.assertEqual(list(message.points[-1].velocities), [0.0] * 6)
        for point in message.points[1:-1]:
            self.assertGreater(np.linalg.norm(point.velocities), 0.0)
        positions = np.asarray([point.positions for point in message.points])
        self.assertLessEqual(np.max(np.abs(np.diff(positions, axis=0))), node.args.max_joint_step)
        final_spoon, final_quat = node.spoon_pose()
        expected_goal = start + node.success_withdraw_direction * 0.10
        self.assertLess(np.linalg.norm(final_spoon - expected_goal), 0.0001)
        self.assertLess((R.from_quat(start_quat[[1, 2, 3, 0]]) * R.from_quat(final_quat[[1, 2, 3, 0]]).inv()).magnitude(), 0.0002)
        # Monitoring a reached goal must not replace the trajectory with holds.
        node.tick()
        self.assertEqual(len(node.commands), 1)
        self.assertFalse(node.success_withdraw_complete)

    def test_feedback_or_controller_loss_pauses_and_still_times_out(self):
        for unavailable in ("data_is_stale", "ros_control_is_ready", "lookup_ee_pose"):
            with self.subTest(unavailable=unavailable):
                node = OfflineDeployNode()
                node.begin_withdrawal()
                setattr(node, unavailable, Mock(return_value={
                    "data_is_stale": True, "ros_control_is_ready": False, "lookup_ee_pose": None
                }[unavailable]))
                with patch("subprocess.Popen") as launch_reset:
                    node.tick()
                    self.assertEqual(node.commands, [])
                    node.now_ns += round(node.SUCCESS_WITHDRAW_TIMEOUT_S * 1e9)
                    node.tick()
                    self.assertTrue(node.episode_stopped)
                    launch_reset.assert_not_called()

    def test_lateral_deviation_or_invalid_pose_cancels_reset(self):
        for invalid in (False, True):
            with self.subTest(invalid_pose=invalid):
                node = OfflineDeployNode()
                node.begin_withdrawal()
                ee_pos, quat = node.lookup_ee_pose()
                ee_pos += np.cross(node.mouth_axis, [0.0, 0.0, 1.0]) * 0.012
                if invalid:
                    quat[0] = np.nan
                node.lookup_ee_pose = Mock(return_value=(ee_pos, quat))
                with patch("subprocess.Popen") as launch_reset:
                    node.tick()
                    self.assertTrue(node.episode_stopped)
                    self.assertFalse(node.success_withdraw_complete)
                    launch_reset.assert_not_called()

